#!/usr/bin/env node
/**
 * Generates the immutable, same-origin precache inventory used by sw.js.
 * Run after changing a page or a file under assets/:
 *   node scripts/generate-offline-manifest.mjs
 */
import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const root = process.cwd();
const toWebPath = value => relative(root, value).split(sep).join("/");
const localReference = /(?:src|href)=["']([^"']+)["']/g;
const ignored = /^(?:https?:|data:|mailto:|tel:|#)/i;

async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? filesIn(path) : path;
  }));
  return files.flat();
}

const pages = (await readdir(root, { withFileTypes: true }))
  .filter(entry => entry.isFile() && entry.name.endsWith(".html"))
  .map(entry => entry.name)
  .sort();
const navigationModules = new Set(["vocabulary", "notes", "reading", "textbook", "review"]);
const navigation = {};
for (const page of pages) {
  const match = page.match(/^chapter-(\d+)-([a-z]+)\.html$/);
  if (!match || !navigationModules.has(match[2])) continue;
  const [, lesson, module] = match;
  (navigation[lesson] ||= {})[module] = page;
}
await writeFile(
  join(root, "assets", "lesson-navigation.json"),
  `${JSON.stringify({ lessons: Object.keys(navigation).map(Number).sort((a, b) => a - b), routes: navigation }, null, 2)}\n`
);
const assets = await filesIn(join(root, "assets"));
const referenced = new Set(pages);

for (const page of pages) {
  const html = await readFile(join(root, page), "utf8");
  for (const match of html.matchAll(localReference)) {
    const url = match[1].split(/[?#]/, 1)[0];
    if (url && !ignored.test(url) && !url.startsWith("/")) referenced.add(url);
  }
}

// The full assets directory is included deliberately: all study data is local
// JavaScript and a future page can safely use a shared asset before this script
// is regenerated.  Exclude non-web artefacts by keeping the app assets folder
// clean; this repository currently contains only app resources there.
for (const asset of assets) {
  const webPath = toWebPath(asset);
  // This file is the generated result, not an application dependency. Including
  // it would make the content hash change on every generation.
  if (webPath !== "assets/offline-assets.js") referenced.add(webPath);
}
referenced.add("manifest.webmanifest");
referenced.add("assets/pwa.js");

const inventory = [...referenced].sort();
const digest = createHash("sha256");
for (const file of inventory) {
  digest.update(file);
  digest.update(await readFile(join(root, file)));
}
const output = `// Generated by scripts/generate-offline-manifest.mjs. Do not edit manually.\nself.JPY5_OFFLINE_MANIFEST = Object.freeze({\n  version: "${digest.digest("hex").slice(0, 16)}",\n  assets: Object.freeze(${JSON.stringify(inventory, null, 2)})\n});\n`;
await mkdir(join(root, "assets"), { recursive: true });
await writeFile(join(root, "assets", "offline-assets.js"), output);
console.log(`Generated ${inventory.length} offline resources.`);
